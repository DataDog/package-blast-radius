func TestTargetsLabel(t *testing.T) {
	pv := func(n, v string) PackageVersion { return PackageVersion{System: NPM, Name: n, Version: v} }

	tests := []struct {
		name    string
		targets []PackageVersion
		want    string
	}{
		{"none", nil, "(none)"},
		{"one", []PackageVersion{pv("axios", "1.14.1")}, "axios@1.14.1"},
		{"three are listed", []PackageVersion{pv("a", "1"), pv("b", "2"), pv("c", "3")}, "a@1, b@2, c@3"},
		{
			"four are summarized",
			[]PackageVersion{pv("a", "1"), pv("a", "2"), pv("b", "1"), pv("c", "1")},
			"4 versions across 3 packages",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := targetsLabel(tt.targets); got != tt.want {
				t.Errorf("targetsLabel() = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestFormatPath(t *testing.T) {
	target := PackageVersion{System: NPM, Name: "axios", Version: "1.14.1"}

	if got := formatPath(nil, target); got != "axios@1.14.1" {
		t.Errorf("empty path = %q, want the bare target", got)
	}

	path := []PathStep{
		{Package: "deep-dep", Version: "2.0.0", Requirement: "^3.11.0"},
		{Package: "tremendous", Version: "3.11.0", Requirement: "^1.6.1"},
	}
	want := "deep-dep@2.0.0 ──(^3.11.0)──▶ tremendous@3.11.0 ──(^1.6.1)──▶ axios@1.14.1"
	if got := formatPath(path, target); got != want {
		t.Errorf("formatPath() = %q, want %q", got, want)
	}
}

// Table output is sorted by downloads, so the most impactful package leads.
func TestRenderTableSortsByImpact(t *testing.T) {
	var buf bytes.Buffer
	if err := RenderResults(sampleResult(), "table", 0, &buf); err != nil {
		t.Fatalf("RenderResults: %v", err)
	}

	out := buf.String()
	if !strings.Contains(out, "2,915,977") {
		t.Errorf("edge count not formatted with separators:\n%s", out)
	}
	if strings.Index(out, "tremendous") > strings.Index(out, "deep-dep") {
		t.Errorf("expected the 24,400-download package to sort above the unenriched one:\n%s", out)
	}
}

func TestRenderAffectedPackagesCSV(t *testing.T) {
	result := &BlastResult{
		Affected: []AffectedPackage{
			{PackageVersion: PackageVersion{Name: "zeta", Version: "1.0.0"}},
			{PackageVersion: PackageVersion{Name: "alpha", Version: "1.10.0"}},
			{PackageVersion: PackageVersion{Name: "alpha", Version: "1.9.0"}},
			{PackageVersion: PackageVersion{Name: "alpha", Version: "1.9.0"}},
			{PackageVersion: PackageVersion{Name: "@scope/pkg", Version: "2.0.0"}},
		},
	}

	var buf bytes.Buffer
	if err := renderAffectedPackagesCSV(result, &buf); err != nil {
		t.Fatalf("renderAffectedPackagesCSV: %v", err)
	}

	raw := buf.String()
	rows, err := csv.NewReader(strings.NewReader(raw)).ReadAll()
	if err != nil {
		t.Fatalf("output is not valid CSV: %v", err)
	}

	want := [][]string{
		{"package_name", "vulnerable_versions"},
		{"@scope/pkg", "2.0.0"},
		// Duplicates collapse and 1.9.0 sorts before 1.10.0.
		{"alpha", "1.9.0,1.10.0"},
		{"zeta", "1.0.0"},
	}
	if !reflect.DeepEqual(rows, want) {
		t.Errorf("got  %q\nwant %q", rows, want)
	}

	// The multi-version field must be quoted, or the file is unparseable.
	if !strings.Contains(raw, `"1.9.0,1.10.0"`) {
		t.Errorf("multi-version field is not quoted:\n%s", raw)
	}
}

// A run's affected-packages.csv is a valid --csv input for the next run.
func TestAffectedPackagesCSVRoundTripsThroughTheParser(t *testing.T) {
	result := &BlastResult{
		Affected: []AffectedPackage{
			{PackageVersion: PackageVersion{Name: "axios", Version: "1.14.1"}},
			{PackageVersion: PackageVersion{Name: "axios", Version: "0.30.4"}},
			{PackageVersion: PackageVersion{Name: "@scope/pkg", Version: "2.0.0"}},
		},
	}

	var buf bytes.Buffer
	if err := renderAffectedPackagesCSV(result, &buf); err != nil {
		t.Fatalf("renderAffectedPackagesCSV: %v", err)
	}

	got, err := ParseCompromisedCSV(writeCSV(t, buf.String()), NPM)
	if err != nil {
		t.Fatalf("ParseCompromisedCSV: %v", err)
	}

	want := []TargetSpec{
		{System: NPM, Name: "@scope/pkg", Versions: []string{"2.0.0"}},
		{System: NPM, Name: "axios", Versions: []string{"0.30.4", "1.14.1"}},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got  %+v\nwant %+v", got, want)
	}
}
