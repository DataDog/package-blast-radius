// JSONResult must round-trip through itself, so a report can be read back with
// the same types that wrote it.
func TestRenderJSONRoundTrips(t *testing.T) {
	var buf bytes.Buffer
	if err := RenderResults(sampleResult(), "json", 0, &buf); err != nil {
		t.Fatalf("RenderResults: %v", err)
	}

	var decoded JSONResult
	if err := json.Unmarshal(buf.Bytes(), &decoded); err != nil {
		t.Fatalf("decoding our own output: %v", err)
	}

	if decoded.System != "NPM" || decoded.TotalEdges != 2915977 || decoded.MaxDepth != 2 {
		t.Errorf("metadata lost: %+v", decoded)
	}
	if len(decoded.Affected) != 2 {
		t.Fatalf("got %d affected, want 2", len(decoded.Affected))
	}
	first := decoded.Affected[0]
	if first.Name != "tremendous" || first.WeeklyDownloads != 24400 || first.Target != "axios@1.14.1" {
		t.Errorf("affected[0] = %+v", first)
	}
	if len(decoded.Affected[1].Path) != 2 {
		t.Errorf("affected[1] path = %+v, want 2 hops", decoded.Affected[1].Path)
	}
}

func TestRenderCSV(t *testing.T) {
	var buf bytes.Buffer
	if err := RenderResults(sampleResult(), "csv", 0, &buf); err != nil {
		t.Fatalf("RenderResults: %v", err)
	}

	lines := strings.Split(strings.TrimRight(buf.String(), "\n"), "\n")
	if len(lines) != 3 {
		t.Fatalf("got %d lines, want header + 2 rows:\n%s", len(lines), buf.String())
	}
	if lines[0] != "package,version,depth,weekly_downloads,target,path" {
		t.Errorf("header = %q", lines[0])
	}
	if !strings.HasPrefix(lines[1], "tremendous,3.11.0,1,24400,axios@1.14.1,") {
		t.Errorf("row 1 = %q", lines[1])
	}
	// An unenriched package (-1) must render as an empty cell, not "-1".
	if !strings.HasPrefix(lines[2], "deep-dep,2.0.0,2,,axios@1.14.1,") {
		t.Errorf("row 2 = %q, want an empty downloads cell", lines[2])
	}
}

// deduplicateByName keeps the first row per name, relying on RenderResults
// having sorted by downloads first.
func TestDeduplicateByName(t *testing.T) {
	affected := []AffectedPackage{
		{PackageVersion: PackageVersion{Name: "a", Version: "2.0.0"}, WeeklyDownloads: 500},
		{PackageVersion: PackageVersion{Name: "a", Version: "1.0.0"}, WeeklyDownloads: 100},
		{PackageVersion: PackageVersion{Name: "b", Version: "1.0.0"}, WeeklyDownloads: 300},
	}

	got := deduplicateByName(affected)

	if len(got) != 2 {
		t.Fatalf("got %d rows, want 2", len(got))
	}
	if got[0].Name != "a" || got[0].Version != "2.0.0" {
		t.Errorf("got[0] = %s@%s, want a@2.0.0 (first occurrence wins)", got[0].Name, got[0].Version)
	}
	if got[1].Name != "b" {
		t.Errorf("got[1] = %s, want b", got[1].Name)
	}
}

