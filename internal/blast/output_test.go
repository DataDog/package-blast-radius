func sampleResult() *BlastResult {
	axios := PackageVersion{System: NPM, Name: "axios", Version: "1.14.1"}
	return &BlastResult{
		Targets:    []PackageVersion{axios},
		TotalEdges: 2915977,
		Affected: []AffectedPackage{
			{
				PackageVersion:  PackageVersion{System: NPM, Name: "tremendous", Version: "3.11.0"},
				Depth:           1,
				Path:            []PathStep{{Package: "tremendous", Version: "3.11.0", Requirement: "^1.6.1"}},
				Target:          axios,
				WeeklyDownloads: 24400,
			},
			{
				PackageVersion: PackageVersion{System: NPM, Name: "deep-dep", Version: "2.0.0"},
				Depth:          2,
				Path: []PathStep{
					{Package: "deep-dep", Version: "2.0.0", Requirement: "^3.11.0"},
					{Package: "tremendous", Version: "3.11.0", Requirement: "^1.6.1"},
				},
				Target:          axios,
				WeeklyDownloads: -1,
			},
		},
		UniquePackages: 2,
		MaxDepth:       2,
		Elapsed:        1500 * time.Millisecond,
	}
}

